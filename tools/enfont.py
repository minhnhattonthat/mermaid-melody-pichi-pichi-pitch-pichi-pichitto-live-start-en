"""enfont.py: the English VWF font (fonts/en12.txt) -> glyph cells, widths, slots and tbl/en.tbl.

    python -X utf8 tools/enfont.py tbl                 # rewrite tbl/en.tbl from the font and the slot plan
    python -X utf8 tools/enfont.py preview OUT.png "Text to typeset" [...]   # render lines with the game palette

Glyphs go into existing single-byte slots of the 12x12 font (docs/re/text.md §Font): the English build draws no
Japanese, except digits, which keep the slots the name charset / number printer use (0x187EA84 entries 0-9).
Cell: 12x12 2bpp, 3 bytes per row, low bits = left pixel. Core row r -> cell row r+1; core pixel = 3 (black),
the pixel right of a core pixel = 2 (dark grey bold). Advance = core width + 2 (bold column + 1 px gap)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "fonts" / "en12.txt"
TBL = ROOT / "tbl" / "en.tbl"
DIGIT_SLOTS = [0xB4, 0x85, 0x9D, 0x97, 0xA2, 0xBD, 0xB9, 0x88, 0xDC, 0xA1]  # name charset codes 0-9
RESERVED = {0x00, 0xAC} | set(DIGIT_SLOTS)  # 00 = blank (blitter special case), AC = name charset 0x15, special in drawchar
MAX_INK = 9  # bold column included: a glyph shifted by up to 3 px must stay inside the 12 px cell
PALETTE = {0: (248, 233, 194), 1: (155, 150, 153), 2: (74, 72, 73), 3: (12, 12, 12)}


def load(path=FONT):
    """-> list of (char, rows) in file order; rows = 10 strings of '#'/'.'."""
    glyphs, cur = [], None
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("#") and cur is None or not line.strip():
            continue
        if line.startswith("== "):
            name = line[3:]
            cur = (" " if name == "space" else name, [])
            glyphs.append(cur)
        elif cur is not None:
            cur[1].append(line)
    for ch, rows in glyphs:
        if len(rows) != 10 or len({len(r) for r in rows}) != 1 or set("".join(rows)) - set("#."):
            raise ValueError(f"glyph {ch!r}: need 10 rows of equal width, '#' and '.' only")
        if len(rows[0]) + 1 > MAX_INK:
            raise ValueError(f"glyph {ch!r}: core width {len(rows[0])} > {MAX_INK - 1}")
    return glyphs


def pixels(rows):
    """-> 12x12 list of 2bpp values."""
    px = [[0] * 12 for _ in range(12)]
    for r, row in enumerate(rows):
        for c, v in enumerate(row):
            if v == "#":
                px[r + 1][c] = 3
                if c + 1 < 12 and (c + 1 >= len(row) or row[c + 1] != "#"):
                    px[r + 1][c + 1] = max(px[r + 1][c + 1], 2)
    return px


def cell(rows):
    out = bytearray()
    for prow in pixels(rows):
        for k in range(0, 12, 4):
            out.append(sum(v << (2 * i) for i, v in enumerate(prow[k:k + 4])))
    return bytes(out)


def width(rows):
    return len(rows[0]) + 2


def slots(glyphs):
    """char -> glyph code. Digits keep their Japanese slots; the rest fill free single-byte slots in font order."""
    free = (c for c in range(1, 0xF0) if c not in RESERVED)
    out = {}
    for ch, _ in glyphs:
        out[ch] = DIGIT_SLOTS[int(ch)] if ch.isdigit() else next(free)
    return out


def tbl_lines(glyphs=None):
    glyphs = glyphs or load()
    lines = ["# Generated by tools/enfont.py from fonts/en12.txt: do not edit. Control codes: tools/msgparse.py."]
    for ch, code in sorted(slots(glyphs).items(), key=lambda kv: kv[1]):
        lines.append(f"{code:02X}={'\\s' if ch == ' ' else ch}")
    return lines


def preview(out, lines, zoom=3):
    from PIL import Image
    glyphs = dict(load())
    w = max(sum(width(glyphs[c]) for c in line) for line in lines) + 8
    img = Image.new("RGB", (w, 12 * len(lines) + 8), PALETTE[0])
    for y, line in enumerate(lines):
        x = 4
        for c in line:
            for r, prow in enumerate(pixels(glyphs[c])):
                for cx, v in enumerate(prow):
                    if v:
                        img.putpixel((x + cx, 4 + 12 * y + r), PALETTE[v])
            x += width(glyphs[c])
    img.resize((img.width * zoom, img.height * zoom), Image.NEAREST).save(out)
    print(out, [sum(width(glyphs[c]) for c in line) for line in lines])


def main():
    if sys.argv[1:2] == ["tbl"]:
        TBL.write_text("\n".join(tbl_lines()) + "\n", encoding="utf-8", newline="\n")
        print(TBL)
    elif sys.argv[1:2] == ["preview"]:
        preview(sys.argv[2], sys.argv[3:])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
